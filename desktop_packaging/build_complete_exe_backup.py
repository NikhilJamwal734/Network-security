"""Build a single Windows EXE from the *currently installed* FirewallAnalyzer tree.

From project root:
  .\\.venv-win\\Scripts\\python.exe .\\desktop_packaging\\build_complete_exe.py

Builds dashboard + optionally standalone logs.html, then bundles Python + UI.
Will not package the user's raw configuration files, logs or source checkout.
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from typing import Iterator


ORIGINAL_CONFIGS = ("vite.config.ts", "vite.config.mts", "vite.config.js", "vite.config.mjs")


def frontend_build_plan(root: Path) -> list[list[str]]:
    frontend = root / "frontend"
    if not (frontend / "package.json").is_file():
        raise FileNotFoundError("Missing frontend/package.json")
    if not (frontend / "index.html").is_file():
        raise FileNotFoundError("Missing frontend/index.html")
    if not (frontend / "node_modules" / "vite").exists():
        raise FileNotFoundError("Missing Vite dependencies. From frontend/ run: npm ci")
    if shutil.which("npm") is None:
        raise FileNotFoundError("npm not found. Install Node.js LTS and restart PowerShell")
    commands = [["npm", "run", "build"]]
    if (frontend / "logs.html").is_file():
        if not (frontend / "src" / "logs-main.tsx").is_file():
            raise FileNotFoundError("frontend/logs.html exists but frontend/src/logs-main.tsx is missing")
        commands.append(["npm", "exec", "--", "vite", "build", "--config", ".firewall-desktop-vite.config.mts"])
    return commands


@contextmanager
def temporary_multipage_config(root: Path) -> Iterator[None]:
    """Only needed for standalone logs.html; temporary, never overwrites user config."""
    frontend = root / "frontend"
    if not (frontend / "logs.html").is_file():
        yield
        return
    config_name = next((n for n in ORIGINAL_CONFIGS if (frontend / n).is_file()), None)
    if config_name is None:
        raise FileNotFoundError("Cannot find a supported frontend/vite.config.ts or equivalent")
    config_path = frontend / ".firewall-desktop-vite.config.mts"
    if config_path.exists() or config_path.is_symlink():
        raise FileExistsError("Temporary Vite config already exists; refusing to overwrite it")
    content = f'''// Temporary multipage production build, generated by FirewallAnalyzer packager.
import original from "./{config_name}";
import {{ defineConfig, mergeConfig }} from "vite";
import {{ resolve }} from "node:path";
export default defineConfig(async env => {{
  const current = typeof original === "function" ? await original(env) : await original;
  return mergeConfig(current, {{ build: {{ rollupOptions: {{ input: {{
    main: resolve(process.cwd(), "index.html"),
    logs: resolve(process.cwd(), "logs.html"),
  }} }} }} }});
}});
'''
    config_path.write_text(content, encoding="utf-8")
    try:
        yield
    finally:
        config_path.unlink(missing_ok=True)


def validate_project(root: Path) -> dict:
    root = root.resolve()
    paths = {
        "backend": root / "app" / "api" / "main.py",
        "frontend": root / "frontend" / "package.json",
        "launcher": root / "desktop_packaging" / "desktop_launcher_complete.py",
    }
    for label, path in paths.items():
        if not path.is_file():
            raise FileNotFoundError(f"Missing {label}: {path}")
    features = {
        "logging": (root / "app" / "core" / "audit_logging.py").is_file(),
        "log_api": (root / "app" / "api" / "log_viewer.py").is_file(),
        "logs_html": (root / "frontend" / "logs.html").is_file(),
        "json_logs_entry": (root / "frontend" / "src" / "logs-main.tsx").is_file(),
        "api_12": (root / "app" / "api" / "release_status.py").is_file(),
    }
    if features["logs_html"] != features["json_logs_entry"]:
        raise ValueError("Incomplete standalone Logs page: logs.html and src/logs-main.tsx must both exist")
    if features["logs_html"] and not features["log_api"]:
        raise ValueError("Logs UI is present but app/api/log_viewer.py is missing")
    if features["log_api"]:
        main = paths["backend"].read_text(encoding="utf-8-sig")
        if "app.api.log_viewer" not in main and "log_viewer import" not in main:
            raise ValueError("Log viewer Python router file exists, but is not wired into app/api/main.py")
    return features


def build_command(root: Path, python: str, *, onefile: bool = True) -> list[str]:
    root = root.resolve()
    dist = root / "frontend" / "dist"
    if not (dist / "index.html").is_file():
        raise FileNotFoundError("Missing compiled frontend/dist/index.html")
    if (root / "frontend" / "logs.html").is_file() and not (dist / "logs.html").is_file():
        raise FileNotFoundError("Logs page is not in frontend/dist/logs.html; multipage build failed")
    base = root / ("desktop_release_single" if onefile else "desktop_release_folder")
    cmd = [python, "-m", "PyInstaller", "--noconfirm", "--clean",
           "--onefile" if onefile else "--onedir", "--console", "--name", "FirewallAnalyzer",
           "--paths", str(root), "--distpath", str(base),
           "--workpath", str(root / ".desktop-complete-build"),
           "--specpath", str(root / ".desktop-complete-build"),
           "--add-data", f"{dist}{os.pathsep}frontend/dist",
           "--collect-submodules", "app", "--collect-submodules", "uvicorn",
           "--hidden-import", "uvicorn.logging", "--hidden-import", "uvicorn.loops.asyncio",
           "--hidden-import", "uvicorn.protocols.http.h11_impl",
           "--hidden-import", "uvicorn.lifespan.on",
           str(root / "desktop_packaging" / "desktop_launcher_complete.py")]
    return cmd


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Package the installed FirewallAnalyzer as a Windows EXE")
    parser.add_argument("--check", action="store_true", help="Check source layout and installed tools without building")
    parser.add_argument("--onedir", action="store_true", help="Produce EXE plus _internal folder instead of a single EXE")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    if sys.platform != "win32" and not args.check:
        print("ERROR: A Windows executable must be built on Windows using Windows Python.", file=sys.stderr)
        return 2
    try:
        features = validate_project(root)
        if importlib.util.find_spec("uvicorn") is None:
            raise RuntimeError("Missing uvicorn. Install backend dependencies in .venv-win")
        if importlib.util.find_spec("PyInstaller") is None and not args.check:
            raise RuntimeError("Missing PyInstaller. Run: .\\.venv-win\\Scripts\\python.exe -m pip install pyinstaller")
        steps = frontend_build_plan(root)
    except (OSError, ValueError, RuntimeError) as exc:
        print("ERROR:", exc, file=sys.stderr)
        return 2
    print("Detected features:", json.dumps(features, indent=2), flush=True)
    if args.check:
        print("Layout check complete. Build commands:", steps)
        if not (root / "frontend" / "dist" / "index.html").is_file():
            print("NOTE: No compiled frontend yet; the regular build will create it")
        return 0
    try:
        with temporary_multipage_config(root):
            for cmd in steps:
                print("Running:", " ".join(cmd), flush=True)
                subprocess.run(cmd, cwd=root / "frontend", check=True)
        command = build_command(root, sys.executable, onefile=not args.onedir)
        print("Packaging current backend and compiled frontend...", flush=True)
        subprocess.run(command, cwd=root, check=True)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print("BUILD FAILED:", exc, file=sys.stderr)
        return 1
    location = (root / "desktop_release_folder" / "FirewallAnalyzer" / "FirewallAnalyzer.exe"
                if args.onedir else root / "desktop_release_single" / "FirewallAnalyzer.exe")
    if not location.is_file():
        print("ERROR: PyInstaller exited successfully but output EXE was not found:", location, file=sys.stderr)
        return 1
    print("BUILD COMPLETE:", location, flush=True)
    print("Run it, test a configuration upload and inspect log output before distribution.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
